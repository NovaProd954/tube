def parse_feed(b):
    root=ET.fromstring(b);out=[]
    cid=(root.findtext('yt:channelId',namespaces=NS) or '')
    for e in root.findall('a:entry',NS):
        vid=e.findtext('yt:videoId',namespaces=NS)
        if not vid:continue
        link=e.find('a:link',NS);href=link.get('href') if link is not None else ''
        st=e.find('m:group/m:community/m:statistics',NS)
        try:t=int(datetime.fromisoformat((e.findtext('a:published',namespaces=NS) or '').replace('Z','+00:00')).timestamp()*1000)
        except Exception:t=-1
        out.append({'url':'/watch?v='+vid,'type':'stream','title':e.findtext('a:title',namespaces=NS) or '','thumbnail':f'https://i.ytimg.com/vi/{vid}/mqdefault.jpg','uploaderName':e.findtext('a:author/a:name',namespaces=NS) or '','uploaderUrl':'/channel/'+(e.findtext('yt:channelId',namespaces=NS) or cid),'uploaderAvatar':None,'uploadedDate':'','uploaded':t,'duration':0,'views':int(st.get('views')) if st is not None and st.get('views') else -1,'uploaderVerified':False,'isShort':'/shorts/' in (href or ''),'livestream':False})
    return out
def http_get(u,t=15):
    req=urllib.request.Request(u,headers=std_headers)
    with urllib.request.urlopen(req,timeout=t) as r:return r.read()
def feed(ids):
    ids=[i for i in ids if re.fullmatch(r'UC[\w-]{22}',i)][:80]
    def one(c):
        try:return cached('rss'+c,600,lambda:parse_feed(http_get('https://www.youtube.com/feeds/videos.xml?channel_id='+c)))
        except Exception:return []
    with ThreadPoolExecutor(8) as ex:res=list(ex.map(one,ids))
    out=[x for r in res for x in r]
    out.sort(key=lambda x:x['uploaded'],reverse=True)
    return out[:150]
def suggest(q):
    if not q:return []
    try:
        j=json.loads(http_get('https://suggestqueries-clients6.youtube.com/complete/search?client=firefox&ds=yt&q='+urllib.parse.quote(q),8).decode('utf-8','replace'))
        return [s for s in j[1] if isinstance(s,str)][:10]
    except Exception:return []
class H(BaseHTTPRequestHandler):
    protocol_version='HTTP/1.1'
    def log_message(self,*a):
        if os.environ.get('TUBE_LOG'):sys.stderr.write('%s\n'%(a[0]%a[1:]))
    def cors(self):
        self.send_header('Access-Control-Allow-Origin','*');self.send_header('Access-Control-Allow-Private-Network','true');self.send_header('Access-Control-Expose-Headers','Content-Range,Content-Length,Accept-Ranges')
    def js(self,obj,code=200,ttl=0):
        b=json.dumps(obj,separators=(',',':')).encode()
        self.send_response(code);self.send_header('Content-Type','application/json; charset=utf-8');self.send_header('Content-Length',str(len(b)));self.send_header('Cache-Control','public, max-age=%d'%ttl if ttl else 'no-store');self.cors();self.end_headers()
        if self.command!='HEAD':self.wfile.write(b)
    def do_OPTIONS(self):
        self.send_response(204);self.cors();self.send_header('Access-Control-Allow-Methods','GET,HEAD,OPTIONS');self.send_header('Access-Control-Allow-Headers','*');self.send_header('Content-Length','0');self.end_headers()
    do_HEAD=lambda self:self.do_GET()
    def do_GET(self):
        p=urllib.parse.urlparse(self.path);q={k:v[0] for k,v in urllib.parse.parse_qs(p.query).items()};path=p.path
        try:
            if path=='/healthcheck':return self.js({'ok':True,'engine':'tube-engine','ytdlp':YV})
            if path=='/trending':return self.js(cached('home',900,lambda:search(CFG['home'],30)['items']))
            if path=='/search':
                qq=q.get('q','').strip()
                if not qq:return self.js({'items':[],'nextpage':None})
                return self.js(cached('s'+qq,300,lambda:search(qq)))
            if path=='/suggestions':return self.js(suggest(q.get('query','')))
            m=re.fullmatch(r'/streams/([\w-]{11})',path)
            if m:
                vid=m.group(1)
                return self.js(cached('v'+vid,1200,lambda:detail(EXTRACT('https://www.youtube.com/watch?v='+vid))))
            m=re.fullmatch(r'/comments/([\w-]{11})',path)
            if m:
                vid=m.group(1)
                return self.js(cached('c'+vid,600,lambda:comments(EXTRACT('https://www.youtube.com/watch?v='+vid,getcomments=True,extractor_args={'youtube':{'max_comments':['20,20,0,0,1'],'comment_sort':['top']}}))))
            m=re.fullmatch(r'/channel/(UC[\w-]{22})',path)
            if m:return self.js(cached('ch'+m.group(1),600,lambda:channel(m.group(1))))
            if path=='/feed/unauthenticated':return self.js(feed(q.get('channels','').split(',')))
            if path=='/proxy':return self.proxy(q.get('u',''),q.get('dl'))
            if path=='/subtitle':return self.subtitle(q.get('u',''))
            self.js({'error':'not found'},404)
        except Exception as e:
            self.js({'error':str(e)[:300]},502)
    def subtitle(self,u):
        if not allowed(u):return self.js({'error':'host not allowed'},403)
        b=http_get(u);self.send_response(200);self.send_header('Content-Type','text/vtt; charset=utf-8');self.send_header('Content-Length',str(len(b)));self.cors();self.end_headers()
        if self.command!='HEAD':self.wfile.write(b)
    def proxy(self,u,dl=None):
        if not allowed(u):return self.js({'error':'host not allowed'},403)
        h=dict(std_headers);h['Referer']='https://www.youtube.com/';h['Origin']='https://www.youtube.com'
        if self.headers.get('Range'):h['Range']=self.headers['Range']
        try:r=urllib.request.urlopen(urllib.request.Request(u,headers=h,method='GET'),timeout=25)
        except urllib.error.HTTPError as e:r=e
        self.send_response(r.status)
        for k in('Content-Type','Content-Length','Content-Range','Accept-Ranges','Cache-Control'):
            v=r.headers.get(k)
            if v:self.send_header(k,v)
        if dl:self.send_header('Content-Disposition',"attachment; filename*=UTF-8''"+urllib.parse.quote(re.sub(r'[\\/:*?"<>|]+','',dl)[:120]))
        self.cors();self.end_headers()
        if self.command=='HEAD':return
        try:
            while True:
                b=r.read(65536)
                if not b:break
                self.wfile.write(b)
        except(BrokenPipeError,ConnectionResetError):pass
def serve(host,port):
    s=ThreadingHTTPServer((host,port),H);s.daemon_threads=True;return s
