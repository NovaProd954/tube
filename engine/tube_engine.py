CACHE={};LOCK=threading.Lock()
def cached(key,ttl,fn):
    now=time.time()
    with LOCK:
        hit=CACHE.get(key)
        if hit and now-hit[0]<ttl:return hit[1]
    val=fn()
    with LOCK:
        CACHE[key]=(now,val)
        if len(CACHE)>400:
            for k in sorted(CACHE,key=lambda k:CACHE[k][0])[:100]:CACHE.pop(k,None)
    return val
def extract(url,**o):
    if yt_dlp is None:raise RuntimeError('yt-dlp is not installed')
