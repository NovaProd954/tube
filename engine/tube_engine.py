def streams(i):
    vs=[];au=[]
    for f in i.get('formats') or []:
        u=f.get('url')
        if not u or f.get('protocol') not in('https','http'):continue
        vc=f.get('vcodec') or 'none';ac=f.get('acodec') or 'none';ext=f.get('ext') or ''
        if vc!='none':
            h=f.get('height') or 0;fps=int(f.get('fps') or 0)
            vs.append({'url':prox(u),'format':ext.upper(),'quality':f"{h}p{fps if fps>30 else ''}",'mimeType':'video/'+('mp4' if ext in('mp4','m4v') else ext),'codec':vc,'videoOnly':ac=='none','bitrate':int((f.get('tbr') or 0)*1000),'width':f.get('width') or 0,'height':h,'fps':fps,'contentLength':f.get('filesize') or f.get('filesize_approx') or 0})
        elif ac!='none':
            au.append({'url':prox(u),'format':ext.upper(),'quality':f"{int(f.get('abr') or 0)} kbps",'mimeType':'audio/'+('mp4' if ext in('m4a','mp4') else ext),'codec':ac,'bitrate':int((f.get('abr') or f.get('tbr') or 0)*1000),'audioTrackId':f.get('language'),'_orig':'original' in (f.get('format_note') or '')})
    if any(a['_orig'] for a in au):au=[a for a in au if a['_orig']]
    for a in au:a.pop('_orig',None)
    return vs,au
def captions(i):
    out=[]
    for auto,src in((False,i.get('subtitles')),(True,i.get('automatic_captions'))):
        for lang,fs in (src or {}).items():
            if auto and not(lang.endswith('-orig') or lang==i.get('language')):continue
            v=next((f for f in fs if f.get('ext')=='vtt'),None)
            if v:out.append({'url':'/subtitle?u='+urllib.parse.quote(v['url'],safe=''),'mimeType':'text/vtt','name':(v.get('name') or lang)+(' (auto)' if auto else ''),'code':lang,'autoGenerated':auto})
    return out[:12]
